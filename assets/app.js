function renderTeachers(lang){
  const dict = translations[lang];
  const grid = document.getElementById('teacherGrid');
  if(!grid) return;
  const label = lang === 'vi' ? (grade)=>`${dict['team.homeroomWord']} ${grade}` :
                lang === 'zh' ? (grade)=>`${grade} ${dict['team.homeroomWord']}` :
                (grade)=>`${grade} ${dict['team.homeroomWord']}`;
  grid.innerHTML = teachers.map(t => `
    <div class="teacher-card">
      <div class="teacher-photo"><img src="${t.img}" alt="${t.name}" loading="lazy"></div>
      <div class="teacher-meta">
        <h4>${t.name}</h4>
        <span>${label(t.grade)}</span>
      </div>
    </div>
  `).join('');
}

function applyLang(lang){
  currentLang = lang;
  localStorage.setItem('lingoinn_lang', lang);
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const key = el.getAttribute('data-i18n-html');
    if(dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    if(dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('#langSwitch button').forEach(b=>{
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });
  renderTeachers(lang);
  document.dispatchEvent(new CustomEvent('lingoinn:langchange', {detail:{lang:lang}}));
}

